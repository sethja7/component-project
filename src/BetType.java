/**
 * Enum to represent different types of bets.
 */
public enum BetType {
    /**
     * Moneyline for team A.
     */
    MONEYLINE_A,
    /**
     * Moneyline for team B.
     */
    MONEYLINE_B,
    /**
     * Spread for team A.
     */
    SPREAD_A,
    /**
     * Spread for team B.
     */
    SPREAD_B
}
